uint32_t keysym_unicode(uint32_t sym)
{
    if ((sym >= 0x20 && sym <= 0x7E) || (sym >= 0xA0 && sym <= 0xFF))
        return sym;
    if (sym >= 0x01000100 && sym <= 0x0110FFFF)
        return sym - 0x01000000;
    if (sym >= 0xFFB0 && sym <= 0xFFB9)
        return '0' + (sym - 0xFFB0);    /* the keypad's digits */
    static const char keypad[] = "*+,-./";
    if (sym >= 0xFFAA && sym <= 0xFFAF)
        return (uint32_t)keypad[sym - 0xFFAA];
    if (sym == 0xFF80)
        return ' ';
    if (sym == 0xFFBD)
        return '=';
    int lo = 0, hi = (int)(sizeof(table) / sizeof(*table)) - 1;
    while (lo <= hi)
    {
        int mid = (lo + hi) / 2;
        if (sym >= table[mid].sym && sym < table[mid].sym + table[mid].count)
            return table[mid].uni + (sym - table[mid].sym);
        if (table[mid].sym < sym)
            lo = mid + 1;
        else
            hi = mid - 1;
    }
    return 0;
}
